#!/usr/bin/env node
// generate-inventory — deterministic repo inventories (Doc 15 R0.2).
//
// Writes three generated docs under docs/inventory/:
//   PACKAGE_GRAPH.md   workspace packages, versions, privacy, internal deps
//   PUBLIC_EXPORTS.md  what each non-private package re-exports from index.ts
//   CLI_COMMANDS.md    top-level `osstack` commands parsed from built --help
//
// Deterministic by construction: no timestamps, no absolute paths, stable
// sorting — so CI can enforce freshness with `--check` (regenerate and fail
// on any diff against the committed docs).
//
// Usage:
//   node scripts/generate-inventory.mjs           write docs/inventory/*
//   node scripts/generate-inventory.mjs --check   fail (exit 1) if stale
//
// Requires packages/cli/dist/bin.js to exist (run after `pnpm -r build`).

import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = join(ROOT, "docs", "inventory");
const HEADER = "<!-- GENERATED by scripts/generate-inventory.mjs — do not edit by hand; re-run the script. -->\n\n";

function readPackages() {
  const packagesDir = join(ROOT, "packages");
  return readdirSync(packagesDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => {
      const manifestPath = join(packagesDir, entry.name, "package.json");
      if (!existsSync(manifestPath)) return undefined;
      const manifest = JSON.parse(readFileSync(manifestPath, "utf-8"));
      const workspaceDeps = Object.entries({ ...manifest.dependencies, ...manifest.devDependencies })
        .filter(([, spec]) => typeof spec === "string" && spec.startsWith("workspace:"))
        .map(([dep]) => dep.replace(/^@osstack\//, ""))
        .sort();
      return {
        dir: entry.name,
        name: manifest.name ?? entry.name,
        version: manifest.version ?? "0.0.0",
        isPrivate: manifest.private === true,
        workspaceDeps,
      };
    })
    .filter((pkg) => pkg !== undefined)
    .sort((a, b) => a.dir.localeCompare(b.dir));
}

function packageGraphDoc(packages) {
  const lines = [
    "# Package Graph",
    "",
    "Workspace packages, publish status, and internal (workspace) dependencies.",
    "",
    "| Package | Version | Visibility | Internal deps |",
    "|---|---|---|---|",
  ];
  for (const pkg of packages) {
    lines.push(`| \`${pkg.name}\` | ${pkg.version} | ${pkg.isPrivate ? "**private**" : "public"} | ${pkg.workspaceDeps.length > 0 ? pkg.workspaceDeps.map((dep) => `\`${dep}\``).join(", ") : "—"} |`);
  }
  lines.push("", "## Edge list", "", "```text");
  for (const pkg of packages) {
    if (pkg.workspaceDeps.length > 0) lines.push(`${pkg.dir} -> ${pkg.workspaceDeps.join(", ")}`);
  }
  lines.push("```", "");
  lines.push("Leaves (no internal deps): " + packages.filter((pkg) => pkg.workspaceDeps.length === 0).map((pkg) => `\`${pkg.dir}\``).join(", "), "");
  return lines.join("\n");
}

function publicExportsDoc(packages) {
  const lines = [
    "# Public Exports",
    "",
    "What each package's `src/index.ts` re-exports (module-level view). Private",
    "packages are listed for completeness but are not a consumable API.",
    "",
  ];
  for (const pkg of packages) {
    const indexPath = join(ROOT, "packages", pkg.dir, "src", "index.ts");
    lines.push(`## \`${pkg.name}\`${pkg.isPrivate ? " (private)" : ""}`, "");
    if (!existsSync(indexPath)) {
      lines.push("_No `src/index.ts` (not a library entry point)._", "");
      continue;
    }
    const exportLines = readFileSync(indexPath, "utf-8")
      .split("\n")
      .filter((line) => line.startsWith("export "));
    if (exportLines.length === 0) {
      lines.push("_`src/index.ts` has no export statements._", "");
      continue;
    }
    lines.push("```ts", ...exportLines, "```", "");
  }
  return lines.join("\n");
}

function cliCommandsDoc() {
  const binPath = join(ROOT, "packages", "cli", "dist", "bin.js");
  if (!existsSync(binPath)) {
    throw new Error("packages/cli/dist/bin.js not found — run `pnpm -r build` first");
  }
  const help = execFileSync("node", [binPath, "--help"], { encoding: "utf-8", env: { ...process.env, NO_COLOR: "1" } });
  // Top-level commands: indented `  <cmd> ...` lines; first token, deduped.
  const commands = [...new Set(
    help.split("\n")
      .map((line) => /^ {2}([a-z][a-z0-9-]*)\b/.exec(line)?.[1])
      .filter((command) => command !== undefined),
  )].sort();

  return [
    "# CLI Commands",
    "",
    `Top-level \`osstack\` commands parsed from \`--help\` (${commands.length} total).`,
    "",
    ...commands.map((command) => `- \`${command}\``),
    "",
    "Doc 15 §2.2 context: this surface is the raw capability layer; the",
    "task-oriented golden paths (`daily` / `start` / `improve`) compose it.",
    "",
  ].join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const packages = readPackages();
  const docs = {
    "PACKAGE_GRAPH.md": HEADER + packageGraphDoc(packages),
    "PUBLIC_EXPORTS.md": HEADER + publicExportsDoc(packages),
    "CLI_COMMANDS.md": HEADER + cliCommandsDoc(),
  };

  mkdirSync(OUT_DIR, { recursive: true });
  let stale = 0;
  for (const [name, content] of Object.entries(docs)) {
    const path = join(OUT_DIR, name);
    const current = existsSync(path) ? readFileSync(path, "utf-8") : undefined;
    if (check) {
      if (current !== content) {
        stale += 1;
        console.error(`stale: docs/inventory/${name} — re-run scripts/generate-inventory.mjs`);
      }
    } else if (current !== content) {
      writeFileSync(path, content, "utf-8");
      console.log(`wrote docs/inventory/${name}`);
    } else {
      console.log(`unchanged docs/inventory/${name}`);
    }
  }
  if (check) {
    if (stale > 0) process.exit(1);
    console.log("inventory: fresh");
  }
}

try {
  main();
} catch (err) {
  console.error(`generate-inventory: ${err instanceof Error ? err.message : String(err)}`);
  process.exit(2);
}
