// Merge retrospective — close the loop after a stack's cards move through the
// board. This renderer is PURE: it takes a plain snapshot of the board's cards
// (+ their checks, final lane, assignee, rework count) and returns a reviewable
// markdown doc that cites which checks caught issues, a one-line memory-fact
// summary, and any missing gates worth proposing. It imports NOTHING from
// @osstack/core — keeping @osstack/loop decoupled from the state layer. Mirrors
// the sectioned-lines style of renderLessonDraft.

export interface StackRetroCheck {
  label: string;
  state: "pending" | "pass" | "fail";
}

export interface StackRetroCard {
  cardId: string;
  title: string;
  cardType: "pr" | "implementation" | "review" | "merge";
  /** Final lane, e.g. "done" | "blocked" | "running". */
  status: string;
  /** Which agent/owner ran it. */
  assignee: string | null;
  checks: StackRetroCheck[];
  /** How many times the card moved backward/into blocked (attempts proxy). */
  reworkCount: number;
}

export interface StackRetroInput {
  board: string;
  cards: StackRetroCard[];
}

export interface StackRetroResult {
  markdown: string;
  /** Every check that ended in state "fail" — the checks that caught issues. */
  caughtIssues: { cardId: string; label: string }[];
  /** One-line summary suitable for a memory fact. */
  memoryFactText: string;
  /** Suggested missing gates (for an optional improvement proposal). Empty when nothing to propose. */
  missingGates: string[];
}

export function renderStackRetro(input: StackRetroInput): StackRetroResult {
  const { board, cards } = input;

  const doneCards = cards.filter((c) => c.status === "done");
  const blockedCount = cards.filter((c) => c.status === "blocked").length;

  const checkTotal = cards.reduce((sum, c) => sum + c.checks.length, 0);
  const passTotal = cards.reduce(
    (sum, c) => sum + c.checks.filter((ck) => ck.state === "pass").length,
    0,
  );

  // caughtIssues: flat list of every card's failing checks, in card order then
  // check order.
  const caughtIssues: { cardId: string; label: string }[] = [];
  for (const c of cards) {
    for (const ck of c.checks) {
      if (ck.state === "fail") {
        caughtIssues.push({ cardId: c.cardId, label: ck.label });
      }
    }
  }

  // Derive next-time gate suggestions deterministically: any failing check whose
  // label mentions the WORD "smoke" or "UI" should have run earlier. Use
  // word-boundary matching (not substring) so "rebuild"/"build"/"guidance" don't
  // spuriously match "ui"/"build"; "endpoint/UI smoke" still matches because
  // "/" and whitespace are word boundaries. The "What To Change Next Time"
  // section repeats a line per failing card (changeLines), while missingGates —
  // which feeds the persisted improvement proposal — is deduped by label; this
  // asymmetry is intentional.
  const missingGates: string[] = [];
  const changeLines: string[] = [];
  const seenGateLabels = new Set<string>();
  for (const issue of caughtIssues) {
    if (!/\bsmoke\b/i.test(issue.label) && !/\bui\b/i.test(issue.label)) continue;
    const sentence = `Add an earlier gate so "${issue.label}" runs before ${issue.cardId} reaches review.`;
    changeLines.push(`- ${sentence}`);
    if (!seenGateLabels.has(issue.label)) {
      seenGateLabels.add(issue.label);
      missingGates.push(sentence);
    }
  }

  const lines: string[] = [
    `# Merge retrospective — board "${board}"`,
    "",
    "> Generated by osstack stack retro. Review before adopting; nothing is auto-merged.",
    "",
    "## Summary",
    `- Cards: ${cards.length} (${doneCards.length} done, ${blockedCount} blocked)`,
    `- Checks: ${passTotal}/${checkTotal} passed`,
    "",
    "## What Worked",
    ...(doneCards.length > 0
      ? doneCards.map((c) => {
          const passCount = c.checks.filter((ck) => ck.state === "pass").length;
          return `- ${c.cardId} ${c.title} — ${passCount}/${c.checks.length} checks passed`;
        })
      : ["- Nothing reached done yet."]),
    "",
    "## What The Checks Caught",
    ...(caughtIssues.length > 0
      ? caughtIssues.map((issue) => `- ${issue.cardId}: ${issue.label} failed`)
      : ["- No failing checks recorded."]),
    "",
    "## Rework",
    ...(cards.some((c) => c.reworkCount > 0)
      ? cards
          .filter((c) => c.reworkCount > 0)
          .map((c) => `- ${c.cardId} reworked ${c.reworkCount}×`)
      : ["- No cards required rework."]),
    "",
    "## Agent Effectiveness",
    ...cards.map((c) => `- ${c.cardId} → ${c.assignee ?? "unassigned"} (${c.cardType})`),
    "",
    "## What To Change Next Time",
    ...(caughtIssues.length > 0
      ? changeLines.length > 0
        ? changeLines
        : ["- Keep the current gate order; no late failures this run."]
      : ["- Keep the current gate order; no late failures this run."]),
    "",
  ];

  const memoryFactText =
    caughtIssues.length > 0
      ? `retro(${board}): ${caughtIssues
          .map((issue) => `${issue.label}@${issue.cardId}`)
          .join(", ")} caught issues; ${passTotal}/${checkTotal} checks passed.`
      : `retro(${board}): clean run, ${passTotal}/${checkTotal} checks passed across ${cards.length} cards.`;

  return {
    markdown: lines.join("\n"),
    caughtIssues,
    memoryFactText,
    missingGates,
  };
}
