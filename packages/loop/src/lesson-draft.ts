// SOP flywheel — turn recovered failures into reviewable lesson drafts.
//
// When a task succeeds after one or more failed attempts, the loop writes a
// draft to loop-lessons/drafts/<task_id>.md. Drafts are review material only:
// official skill files are never modified automatically.

import { mkdir, readFile, readdir, rename, writeFile } from "node:fs/promises";
import { basename, dirname, isAbsolute, join } from "node:path";
import { z } from "zod";
import { isSkillTask, skillIdOf } from "./publisher.js";
import type { IterationFeedback, Task, Verdict } from "./types.js";

export const LessonDraftConfig = z.object({
  enabled: z.boolean().default(true),
  dir: z.string().default("loop-lessons/drafts"),
});
export type LessonDraftConfig = z.infer<typeof LessonDraftConfig>;

export interface LessonDraftInput {
  task: Task;
  /** Total attempts the task took, including the successful one. */
  iterations: number;
  /** Feedback derived from each failed attempt, in attempt order. */
  feedback: readonly IterationFeedback[];
  finalVerdict?: Verdict | null;
  changedFiles?: readonly string[];
  diffSummary?: string;
  commitHash?: string;
}

export interface LessonDraftResult {
  written: boolean;
  path?: string;
  reason?: string;
}

/** Drafts are only useful when the verifier actually rejected an earlier attempt. */
export function shouldDraftLesson(input: Pick<LessonDraftInput, "feedback">): boolean {
  return input.feedback.length > 0;
}

export function renderLessonDraft(input: LessonDraftInput): string {
  const { task, feedback } = input;
  const failedEvaluationIds = [...new Set(feedback.flatMap((entry) => entry.failed_evaluations))];
  const verifierCatches = feedback.map((entry) => {
    const issues = entry.blocking_issues.length === 0
      ? "verification did not pass"
      : entry.blocking_issues.map((issue) => issue.message).join("; ");
    return `- Attempt ${entry.attempt}: ${issues}`;
  });
  const focus = [...new Set(feedback.flatMap((entry) => entry.suggested_focus))];
  const suggestedEvaluations = suggestedEvaluationLines(input, failedEvaluationIds);
  const skillId = isSkillTask(task) ? skillIdOf(task) : undefined;

  const lines = [
    `# Lesson Draft: ${task.task_id}`,
    "",
    `> Generated by osstack loop: task succeeded on attempt ${input.iterations} after ${feedback.length} failed attempt(s).`,
    "> Review before adopting. Official skill files are never modified automatically.",
    "",
    "## Task Prompt",
    task.prompt,
    "",
    "## Failed Evaluations",
    ...(failedEvaluationIds.length > 0
      ? failedEvaluationIds.map((id) => `- ${id}`)
      : ["- None recorded (verification failed without evaluation specs)"]),
    "",
    "## What The Verifier Caught",
    ...verifierCatches,
    "",
    "## Final Fix Summary",
    `- Outcome: success after ${input.iterations} iteration(s)`,
    ...(input.diffSummary !== undefined ? [`- Diff: ${input.diffSummary}`] : []),
    ...(input.changedFiles !== undefined && input.changedFiles.length > 0
      ? [`- Changed files: ${input.changedFiles.join(", ")}`]
      : []),
    ...(input.commitHash !== undefined ? [`- Commit: ${input.commitHash}`] : []),
    ...(input.finalVerdict != null ? [`- Final verdict: ${input.finalVerdict.summary}`] : []),
    "",
    "## Reusable Rule",
    reusableRule(task, failedEvaluationIds, focus),
    "",
    "## Suggested Evaluation",
    ...suggestedEvaluations,
    "",
    "## Suggested Target Skill",
    skillId !== undefined ? `- ${skillId}` : "- Not inferable from task context",
    "",
  ];
  return lines.join("\n");
}

export async function writeLessonDraft(
  input: LessonDraftInput,
  options: { workspacePath: string; config?: Partial<LessonDraftConfig> },
): Promise<LessonDraftResult> {
  const config = LessonDraftConfig.parse(options.config ?? {});
  if (!config.enabled) return { written: false, reason: "lesson drafts disabled" };
  if (!shouldDraftLesson(input)) {
    return { written: false, reason: "task succeeded without failed attempts; nothing to learn" };
  }

  const dir = isAbsolute(config.dir) ? config.dir : join(options.workspacePath, config.dir);
  const path = join(dir, `${sanitizeFileName(input.task.task_id)}.md`);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, renderLessonDraft(input), "utf-8");
  return { written: true, path };
}

function reusableRule(task: Task, failedEvaluationIds: string[], focus: string[]): string {
  const subject = `tasks like "${task.capability}"`;
  const evaluationClause = failedEvaluationIds.length > 0
    ? `make the ${failedEvaluationIds.join(", ")} evaluation(s) pass before claiming completion`
    : "re-run the verifier before claiming completion";
  const focusClause = focus.length > 0 ? ` Pay attention to: ${focus.join("; ")}.` : "";
  return `When working on ${subject}, ${evaluationClause}.${focusClause} (Draft rule — refine before adding to a skill.)`;
}

function suggestedEvaluationLines(input: LessonDraftInput, failedEvaluationIds: string[]): string[] {
  const lines: string[] = [];
  const specs = input.task.evaluation ?? [];
  for (const spec of specs) {
    if (!failedEvaluationIds.includes(spec.id)) continue;
    lines.push(spec.command !== undefined
      ? `- Run \`${spec.command}\` (${spec.id})`
      : `- Require ${spec.mode} review: ${spec.description} (${spec.id})`);
  }
  for (const id of failedEvaluationIds) {
    if (specs.some((spec) => spec.id === id)) continue;
    lines.push(`- Keep the ${id} check as a required evaluation`);
  }
  if (lines.length === 0) {
    lines.push("- Add an evaluation spec that would have caught the first failed attempt");
  }
  return lines;
}

function sanitizeFileName(value: string): string {
  const sanitized = value.replace(/[^a-zA-Z0-9._-]+/g, "-").replace(/^-+|-+$/g, "");
  return sanitized === "" ? "lesson" : sanitized.slice(0, 80);
}

// ── Review workflow: list / read / promote / discard ────────────────────
//
// Drafts wait in loop-lessons/drafts/ until a human reviews them.
// Promoting moves a draft to loop-lessons/promoted/ and, ONLY with an
// explicit target skill path, appends the lesson to that file. Discarding
// moves it to loop-lessons/discarded/. The loop itself never promotes.

export interface LessonDraftEntry {
  id: string;
  path: string;
  title: string;
  suggested_skill?: string;
}

export interface PromoteLessonDraftResult {
  promoted: boolean;
  from?: string;
  to?: string;
  appended_to?: string;
  reason?: string;
}

export interface DiscardLessonDraftResult {
  discarded: boolean;
  from?: string;
  to?: string;
  reason?: string;
}

export async function listLessonDrafts(
  workspacePath: string,
  dir = "loop-lessons/drafts",
): Promise<LessonDraftEntry[]> {
  const draftDir = resolveLessonDir(workspacePath, dir);
  let entries: string[];
  try {
    entries = await readdir(draftDir);
  } catch {
    return [];
  }
  const drafts: LessonDraftEntry[] = [];
  for (const entry of entries.sort()) {
    if (!entry.endsWith(".md")) continue;
    const path = join(draftDir, entry);
    try {
      drafts.push(parseLessonDraftEntry(path, await readFile(path, "utf-8")));
    } catch {
      // Skip unreadable drafts; listing must not fail on one bad file.
    }
  }
  return drafts;
}

export async function readLessonDraft(
  workspacePath: string,
  id: string,
  dir = "loop-lessons/drafts",
): Promise<{ entry: LessonDraftEntry; content: string } | null> {
  const path = join(resolveLessonDir(workspacePath, dir), `${sanitizeFileName(id)}.md`);
  try {
    const content = await readFile(path, "utf-8");
    return { entry: parseLessonDraftEntry(path, content), content };
  } catch {
    return null;
  }
}

export async function promoteLessonDraft(
  workspacePath: string,
  id: string,
  options: { dir?: string; promotedDir?: string; toSkillPath?: string } = {},
): Promise<PromoteLessonDraftResult> {
  const draft = await readLessonDraft(workspacePath, id, options.dir ?? "loop-lessons/drafts");
  if (draft === null) return { promoted: false, reason: `no lesson draft found for id ${id}` };

  if (options.toSkillPath !== undefined) {
    const skillPath = isAbsolute(options.toSkillPath)
      ? options.toSkillPath
      : join(workspacePath, options.toSkillPath);
    let existing: string;
    try {
      existing = await readFile(skillPath, "utf-8");
    } catch {
      return { promoted: false, reason: `target skill file not found: ${options.toSkillPath}` };
    }
    const rule = extractLessonSection(draft.content, "## Reusable Rule");
    const evaluation = extractLessonSection(draft.content, "## Suggested Evaluation");
    const appended = [
      existing.endsWith("\n") ? existing : `${existing}\n`,
      `\n## Lesson: ${draft.entry.id}\n`,
      "\n",
      rule ?? "(no reusable rule recorded)",
      "\n",
      ...(evaluation !== undefined ? ["\n### Suggested Evaluation\n\n", evaluation, "\n"] : []),
    ].join("");
    await writeFile(skillPath, appended, "utf-8");
  }

  const promotedDir = resolveLessonDir(workspacePath, options.promotedDir ?? "loop-lessons/promoted");
  await mkdir(promotedDir, { recursive: true });
  const to = join(promotedDir, basename(draft.entry.path));
  await rename(draft.entry.path, to);
  return {
    promoted: true,
    from: draft.entry.path,
    to,
    ...(options.toSkillPath !== undefined ? { appended_to: options.toSkillPath } : {}),
  };
}

export async function discardLessonDraft(
  workspacePath: string,
  id: string,
  options: { dir?: string; discardedDir?: string } = {},
): Promise<DiscardLessonDraftResult> {
  const draft = await readLessonDraft(workspacePath, id, options.dir ?? "loop-lessons/drafts");
  if (draft === null) return { discarded: false, reason: `no lesson draft found for id ${id}` };
  const discardedDir = resolveLessonDir(workspacePath, options.discardedDir ?? "loop-lessons/discarded");
  await mkdir(discardedDir, { recursive: true });
  const to = join(discardedDir, basename(draft.entry.path));
  await rename(draft.entry.path, to);
  return { discarded: true, from: draft.entry.path, to };
}

function parseLessonDraftEntry(path: string, content: string): LessonDraftEntry {
  const id = basename(path).replace(/\.md$/, "");
  const titleMatch = content.match(/^# Lesson Draft: (.+)$/m);
  const skillSection = extractLessonSection(content, "## Suggested Target Skill");
  const skillLine = skillSection?.split("\n").find((line) => line.startsWith("- "));
  const skill = skillLine?.slice(2).trim();
  return {
    id,
    path,
    title: titleMatch?.[1]?.trim() ?? id,
    ...(skill !== undefined && !skill.startsWith("Not inferable") ? { suggested_skill: skill } : {}),
  };
}

function extractLessonSection(content: string, heading: string): string | undefined {
  const lines = content.split("\n");
  const start = lines.findIndex((line) => line.trim() === heading);
  if (start === -1) return undefined;
  const rest = lines.slice(start + 1);
  const end = rest.findIndex((line) => line.startsWith("## "));
  const section = (end === -1 ? rest : rest.slice(0, end)).join("\n").trim();
  return section === "" ? undefined : section;
}

function resolveLessonDir(workspacePath: string, dir: string): string {
  return isAbsolute(dir) ? dir : join(workspacePath, dir);
}
