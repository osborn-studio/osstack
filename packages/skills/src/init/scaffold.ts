// `osstack init` — V2 equivalent of V1 osb-init.
//
// Creates the OSBORN project skeleton in the current directory:
//   .agent/PROJECT_CONTEXT.md   — context refreshed by `osstack context`
//   docs/PRD.md, docs/ARCHITECTURE.md, docs/SPRINTS.md — empty stubs
//   tasks/                     — empty dir for `osstack task add` (V1 osb-task)
//   AGENTS.md                  — top-level skill manifest
//
// All file writes are skip-if-exists so it's safe to run on an existing repo.

import { mkdirSync, writeFileSync, existsSync } from "node:fs";
import { join, basename, resolve } from "node:path";

const PROJECT_CONTEXT_TEMPLATE = `# Project Context
> Generated by \`osstack init\`. Refresh with \`osstack context\`.

**Project:** {{NAME}}
**Created:** {{DATE}}

## Mission
_(one sentence)_

## Stack
_(language, runtime, key libs)_

## Constraints
_(deadlines, dependencies, must-not-do)_

## Open questions
- _(thing the team hasn't decided yet)_
`;

const AGENTS_MD_TEMPLATE = `# Agents

This project is managed by **osstack** (Hermes skill).
See https://github.com/gilosbornhello/osbstack for the runtime.

## How to use

\`\`\`bash
osstack task submit "describe what to do"
osstack stats
osstack hermes dashboard
\`\`\`

## Conventions

- All task prompts go through osstack so we get cross-task memory + routing.
- Edit \`.agent/PROJECT_CONTEXT.md\` to keep agents grounded in this project.
- Decisions land in \`docs/ARCHITECTURE.md\` so they outlive any session.
`;

const PRD_TEMPLATE = `# Product Requirements

> Add the high-level intent here. Keep it under one page.

## Problem
_(who has this problem, what changes if we solve it)_

## Out of scope
_(things we are explicitly NOT doing)_

## Success metrics
_(observable outcomes)_
`;

const ARCH_TEMPLATE = `# Architecture

> Record decisions, not implementation details. Use ADR-style entries below.

## ADR-001: Use osstack for task orchestration
- **Status:** Accepted
- **Context:** Need durable task history + multi-agent routing.
- **Decision:** Route all sub-agent calls through osstack.
- **Consequences:** Tasks, runs, events persist in \`~/.osstack/state.db\`.
`;

const SPRINTS_TEMPLATE = `# Sprints

> One section per sprint. Keep entries short — link out for detail.

## Sprint 0 — Setup
- [ ] Run \`osstack init\` in repo root.
- [ ] Fill in \`docs/PRD.md\`.
`;

export interface InitResult {
  created: string[];
  skipped: string[];
  project: string;
}

export function initProject(dir: string = process.cwd()): InitResult {
  const absDir = resolve(dir);
  const project = basename(absDir);
  const created: string[] = [];
  const skipped: string[] = [];
  const today = new Date().toISOString().slice(0, 10);

  const ensureDir = (path: string): void => {
    if (existsSync(path)) { skipped.push(path); return; }
    mkdirSync(path, { recursive: true });
    created.push(path);
  };
  const ensureFile = (path: string, contents: string): void => {
    if (existsSync(path)) { skipped.push(path); return; }
    writeFileSync(path, contents);
    created.push(path);
  };

  ensureDir(join(absDir, ".agent"));
  ensureDir(join(absDir, "docs"));
  ensureDir(join(absDir, "tasks"));

  ensureFile(
    join(absDir, ".agent", "PROJECT_CONTEXT.md"),
    PROJECT_CONTEXT_TEMPLATE.replace("{{NAME}}", project).replace("{{DATE}}", today),
  );
  ensureFile(join(absDir, "AGENTS.md"), AGENTS_MD_TEMPLATE);
  ensureFile(join(absDir, "docs", "PRD.md"), PRD_TEMPLATE);
  ensureFile(join(absDir, "docs", "ARCHITECTURE.md"), ARCH_TEMPLATE);
  ensureFile(join(absDir, "docs", "SPRINTS.md"), SPRINTS_TEMPLATE);

  return { created, skipped, project };
}
